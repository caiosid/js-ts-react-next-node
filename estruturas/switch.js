// Estrutura condicinal: switch
const job = "Engenheiro";

switch (job) {
  case "Padeiro":
    console.log("Você é um programador");
    break;
  case "Advogado":
    console.log("Você é um advogado");
    break;

  case "Programador":
    console.log("Você é um programador");
    break;

  default:
    console.log("Profissão não encontrada");
}
